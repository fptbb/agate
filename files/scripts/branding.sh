#!/usr/bin/env bash
set -euo pipefail

# Preserve the original build-command logging, unless shell tracing is requested.
if [[ -n "${SET_X:-}" ]]; then
    set -x
else
    trap '[[ $BASH_COMMAND == echo\ * || $BASH_COMMAND == log\ * ]] || echo "+ $BASH_COMMAND"' DEBUG
fi

log() {
    echo "=== $* ==="
}

# Channel is supplied by the recipe (AGATE_CHANNEL), defaulting to latest.
CHANNEL="${AGATE_CHANNEL:-latest}"
case "$CHANNEL" in
    latest)  CHANNEL_LABEL="Stable" ;;
    testing) CHANNEL_LABEL="Testing" ;;
    *)
        log "Unknown AGATE_CHANNEL: $CHANNEL"
        exit 1
        ;;
esac

OS_RELEASE="/usr/lib/os-release"
IMAGE_INFO="/usr/share/ublue-os/image-info.json"
IMAGE_REF="ostree-image-signed:docker://quay.io/fpsys/agate"
IMAGE_TAG="$CHANNEL"
IMAGE_BRANCH="$CHANNEL"

# Load dynamic values generated by the base image.
# shellcheck disable=SC1090
. "$OS_RELEASE"
: "${OSTREE_VERSION:?Missing OSTREE_VERSION in $OS_RELEASE}"
IMAGE_VERSION="${OSTREE_VERSION%.*}"

# -------------------------
# image-info.json
# -------------------------

# Replace only the quoted value of each property. Matching up to a comma
# can corrupt the JSON when the property is the last one in the object.
FEDORA_VERSION="${OSTREE_VERSION%%.*}"
sed -i \
    -e 's/"image-name": *"[^"]*"/"image-name": "agate"/' \
    -e 's/"image-vendor": *"[^"]*"/"image-vendor": "fptbb"/' \
    -e "s|\"image-tag\": *\"[^\"]*\"|\"image-tag\": \"${IMAGE_TAG}\"|" \
    -e "s|\"image-branch\": *\"[^\"]*\"|\"image-branch\": \"${IMAGE_BRANCH}\"|" \
    -e "s|\"version-pretty\": *\"[^\"]*\"|\"version-pretty\": \"${CHANNEL_LABEL} (F${FEDORA_VERSION})\"|" \
    -e "s|\"image-ref\": *\"[^\"]*\"|\"image-ref\": \"${IMAGE_REF}\"|" \
    "$IMAGE_INFO"

# -------------------------
# /usr/lib/os-release
# -------------------------

# Remove Bazzite-specific CPE and support/documentation URLs.
sed -i '/^CPE_NAME=/d; /^DOCUMENTATION_URL=/d; /^SUPPORT_URL=/d; /^BUG_REPORT_URL=/d' "$OS_RELEASE"

# Point the distro logo at the new Agate icon theme name.
if grep -q '^LOGO=' "$OS_RELEASE"; then
    sed -i 's/^LOGO=.*/LOGO=agate-logo-icon/' "$OS_RELEASE"
else
    printf '\nLOGO=agate-logo-icon\n' >> "$OS_RELEASE"
fi

# Dynamic values derived from the base image version.
sed -i \
    "s/^BOOTLOADER_NAME=.*/BOOTLOADER_NAME=\"Agate ${CHANNEL_LABEL} (F${IMAGE_VERSION})\"/" \
    "$OS_RELEASE"

sed -i \
    "s/^IMAGE_ID=.*/IMAGE_ID=\"agate-${IMAGE_VERSION}\"/" \
    "$OS_RELEASE"

# -------------------------
# yafti (first-boot portal)
# -------------------------

YAFTI_CONFIG="/usr/share/yafti/yafti.yml"
sed -i 's/^title: Bazzite Portal/title: System Utilities/' "$YAFTI_CONFIG"

# Avoid duplicating the Agate section if a build step executes twice.
if ! grep -q 'title: "Agate Utilities"' "$YAFTI_CONFIG"; then
    sed -i '/^screens:/a\
  - title: "Agate Utilities"\
    description: "Agate-specific installers and maintenance tools"\
    actions:\
      - id: "agate-devbox"\
        title: "Install DevBox"\
        description: "Installs DevBox for disposable development environments."\
        default: false\
        script: "ujust agate-devbox"\
      - id: "dotfiles-update"\
        title: "Update Dotfiles"\
        description: "Pulls dotfiles changes from the repo and applies them locally. This can overwrite or remove local files."\
        default: false\
        script: "ujust dotfiles-update"\
      - id: "dotfiles-apply"\
        title: "Apply Dotfiles"\
        description: "Applies the repo state to this system. This can overwrite or remove local files."\
        default: false\
        script: "ujust dotfiles-apply"\
      - id: "dotfiles-status"\
        title: "Dotfiles Status"\
        description: "Shows what files are currently changed before syncing or applying."\
        default: false\
        script: "ujust dotfiles-status"\
      - id: "dotfiles-diff"\
        title: "Dotfiles Diff"\
        description: "Shows the exact line-by-line changes before syncing or applying."\
        default: false\
        script: "ujust dotfiles-diff"\
      - id: "dotfiles-sync"\
        title: "Dotfiles Sync"\
        description: "Pushes local computer changes into the dotfiles repo. Check status and diff first to avoid syncing unwanted changes."\
        default: false\
        script: "ujust dotfiles-sync"\
      - id: "agate-gpg-reload"\
        title: "Reload GPG Stack"\
        description: "Restarts the smartcard and GPG services."\
        default: false\
        script: "ujust agate-gpg-reload"\
' "$YAFTI_CONFIG"
fi

# -------------------------
# Icons and branding
# -------------------------

log "Installing Agate icons"
PIXMAPS="/usr/share/pixmaps"
ICONS="/usr/share/icons/hicolor"
APPS="${ICONS}/scalable/apps"
PLACES="${ICONS}/scalable/places"

# theming.sh installs all pixmaps from assets; branding only needs the
# Agate SVG variants. Original Fedora assets remain untouched.
command -v rsvg-convert >/dev/null 2>&1 || {
    log 'Missing librsvg2-tools (rsvg-convert)'
    exit 1
}

link_to() {
    local source="$1" destination="$2"
    install -d "$(dirname "$destination")"
    ln -sfnT "$source" "$destination"
}

for variant in '' '-le' '-white'; do
    source="${PIXMAPS}/agate-logo${variant}.svg"
    [[ -s "$source" ]] || {
        log "Missing required artwork: $source (check theming.sh assets)"
        exit 1
    }
    link_to "agate-logo${variant}.svg" "${PIXMAPS}/fp-logo${variant}.svg"
done

# SVG aliases used by GTK, KDE and Bazzite.
for name in agate-logo-icon fedora-logo-icon bazzite-logo-icon start-here; do
    link_to "${PIXMAPS}/agate-logo.svg" "${APPS}/${name}.svg"
done
for name in agate-logo bazzite-logo distributor-logo distributor-logo-steamdeck start-here; do
    link_to "${PIXMAPS}/agate-logo.svg" "${PLACES}/${name}.svg"
done
link_to "${PIXMAPS}/agate-logo-le.svg" "${PLACES}/bazzite-logo-le.svg"
for name in bazzite-logo-white distributor-logo-white; do
    link_to "${PIXMAPS}/agate-logo-white.svg" "${PLACES}/${name}.svg"
done

# Build one PNG per icon size; legacy names are symlinks, not duplicates.
for size in 16 22 24 32 36 48 96 256; do
    size_dir="${ICONS}/${size}x${size}"
    install -d "${size_dir}/apps" "${size_dir}/places"

    rsvg-convert \
        --width "$size" --height "$size" \
        --output "${size_dir}/apps/agate-logo-icon.png" \
        "${PIXMAPS}/agate-logo.svg"

    for name in fedora-logo-icon bazzite-logo-icon; do
        link_to 'agate-logo-icon.png' "${size_dir}/apps/${name}.png"
    done

    # Bazzite's original PNGs are directly inside the size directory.
    link_to 'apps/agate-logo-icon.png' "${size_dir}/bazzite-logo-icon.png"
    link_to '../apps/agate-logo-icon.png' "${size_dir}/places/start-here.png"
done

# The white variant is only needed by the system-logo-white pixmap alias.
rsvg-convert \
    --width 256 --height 256 \
    --output "${ICONS}/256x256/apps/agate-logo-white.png" \
    "${PIXMAPS}/agate-logo-white.svg"

# Generate ONLY these three PNG aliases. fedora-logo.png and the other
# Fedora/bootloader originals are installed verbatim from the assets branch.
normal_256="${ICONS}/256x256/apps/agate-logo-icon.png"
white_256="${ICONS}/256x256/apps/agate-logo-white.png"

link_to "$normal_256" "${PIXMAPS}/fp-logo.png"
link_to "$normal_256" "${PIXMAPS}/faces/fp-logo.png"
link_to "$white_256"  "${PIXMAPS}/system-logo-white.png"

# Preserve all other pixmaps exactly as supplied by the Agate assets branch.

if command -v gtk-update-icon-cache >/dev/null 2>&1; then
    gtk-update-icon-cache -f "$ICONS"
fi

# -------------------------
# Sessions
# -------------------------

# Remove Deck Mode and one-shot Plasma session entries.
rm -f \
    /usr/share/wayland-sessions/gamescope-session.desktop \
    /usr/share/wayland-sessions/steam-plus.desktop \
    /usr/share/wayland-sessions/plasma-steamos-wayland-oneshot.desktop \
    /usr/share/xsessions/plasma-steamos-oneshot.desktop

log "Agate branding installed"
